export function interpolateTrackPoint(
  track: TrackProfile,
  lapDistPct: number
): { x: number; y: number } {
  return interpolatePoints(track.pathPoints, lapDistPct);
}

export function getActiveCorner(
  track: TrackProfile,
  lapDistPct: number
): CornerDefinition | null {
  const pct = ((lapDistPct % 1) + 1) % 1;
  for (const c of track.corners) {
    if (pct >= c.startPct - 0.015 && pct <= c.exitPct + 0.01) {
      return c;
    }
  }
  return null;
}

export function getUpcomingCorner(
  track: TrackProfile,
  lapDistPct: number
): CornerDefinition {
  const pct = ((lapDistPct % 1) + 1) % 1;
  const next = track.corners.find((c) => c.exitPct >= pct);
  return next ?? track.corners[0];
}

export function buildReferenceLap(track: TrackProfile, car: CarProfile): ReferenceSample[] {
  const count = 240;
  const samples: ReferenceSample[] = [];
  const scaleSpeed = car.topSpeedKmh / 338;

  for (let i = 0; i < count; i++) {
    const pct = i / count;
    let speed = car.topSpeedKmh * 0.94;
    let throttle = 1.0;
    let brake = 0.0;
    let steeringRad = 0.0;

    for (const c of track.corners) {
      const entrySpeed = c.targetEntrySpeedKmh * scaleSpeed;
      const apexSpeed = c.targetApexSpeedKmh * scaleSpeed;

      if (pct >= c.brakeMarkerPct && pct <= c.apexPct) {
        const t = (pct - c.brakeMarkerPct) / Math.max(0.001, c.apexPct - c.brakeMarkerPct);
        const decel = Math.sin((t * Math.PI) / 2);
        speed = entrySpeed - (entrySpeed - apexSpeed) * decel;
        brake = Math.max(0, c.targetBrakePressure * (1 - t * 0.72));
        throttle = 0.0;
        steeringRad = (c.number % 2 === 0 ? 1 : -1) * Math.sin(t * Math.PI * 0.5) * 0.34;
        break;
      } else if (pct > c.apexPct && pct <= c.exitPct) {
        const t = (pct - c.apexPct) / Math.max(0.001, c.exitPct - c.apexPct);
        const exitTarget = Math.min(car.topSpeedKmh * 0.85, apexSpeed + 95);
        speed = apexSpeed + (exitTarget - apexSpeed) * Math.pow(t, 0.85);
        brake = 0.0;
        throttle = Math.min(1.0, 0.25 + t * 0.82);
        steeringRad = (c.number % 2 === 0 ? 1 : -1) * (1 - t) * 0.28;
        break;
      } else if (pct >= c.startPct - 0.025 && pct < c.brakeMarkerPct) {
        speed = entrySpeed;
        throttle = 1.0;
        brake = 0.0;
        steeringRad = 0.0;
        break;
      }
    }

    const gear =
      speed < 85
        ? 1
        : speed < 130
          ? 2
          : speed < 175
            ? 3
            : speed < 220
              ? 4
              : speed < 268
                ? 5
                : speed < 308
                  ? 6
                  : 7;

    const rpm = Math.round(
      Math.min(car.maxRpm - 180, Math.max(4200, car.shiftRpm * (0.68 + (speed % 52) / 140)))
    );

    samples.push({
      pct,
      speedKmh: Math.round(speed * 10) / 10,
      throttle: Math.round(throttle * 100) / 100,
      brake: Math.round(brake * 100) / 100,
      steeringRad: Math.round(steeringRad * 1000) / 1000,
      gear,
      rpm,
    });
  }

  return samples;
}

export function buildSampleUserLap(track: TrackProfile, car: CarProfile): LapRecord {
  const ref = buildReferenceLap(track, car);
  const frames: TelemetryFrame[] = [];
  let cumulativeDelta = 0;

  for (let i = 0; i < ref.length; i++) {
    const r = ref[i];
    let brakeOffset = 0;
    let speedOffset = 0;
    let throttleOffset = 0;
    let frontSlip = 0.03;

    const corner = getActiveCorner(track, r.pct);
    if (corner) {
      if (corner.number <= 5 || corner.number === 9 || corner.number === 7) {
        const pastBrake = r.pct - corner.brakeMarkerPct;
        if (pastBrake > 0 && pastBrake < 0.008) {
          brakeOffset = -0.35;
          speedOffset = 14;
          cumulativeDelta += 0.012;
        } else if (pastBrake >= 0.008 && r.pct < corner.apexPct) {
          brakeOffset = 0.12;
          speedOffset = -6;
          frontSlip = 0.19;
          cumulativeDelta += 0.018;
        }
      } else {
        throttleOffset = -0.14;
        speedOffset = -5;
        cumulativeDelta += 0.008;
      }
    }

    const speedKmh = Math.max(45, Math.min(car.topSpeedKmh, r.speedKmh + speedOffset));
    const brake = Math.max(0, Math.min(1, r.brake + brakeOffset));
    const throttle = Math.max(0, Math.min(1, r.throttle + throttleOffset));

    frames.push({
      timestampMs: i * 850,
      lapNumber: 1,
      lapDistPct: r.pct,
      speedKmh: Math.round(speedKmh * 10) / 10,
      rpm: r.rpm,
      maxRpm: car.maxRpm,
      gear: r.gear,
      throttle,
      brake,
      steeringRad: r.steeringRad * 1.08,
      latG: Math.round(r.steeringRad * (speedKmh / 110) * 100) / 100,
      longG: Math.round((throttle * 1.15 - brake * 2.85) * 100) / 100,
      deltaSec: Math.round(cumulativeDelta * 1000) / 1000,
      fuelLiters: Math.max(12, 68.4 - i * 0.02),
      tireTempC: { fl: 86, fr: 84, rl: 82, rr: 81 },
      tirePressurePsi: { fl: 26.8, fr: 26.6, rl: 26.2, rr: 26.1 },
      tireWearPct: { fl: 96.4, fr: 96.8, rl: 97.2, rr: 97.4 },
      brakeTempC: { fl: 480 + brake * 240, fr: 475 + brake * 235, rl: 390, rr: 385 },
      frontWheelSlip: frontSlip,
      rearWheelSlip: throttle > 0.85 && Math.abs(r.steeringRad) > 0.2 ? 0.14 : 0.03,
      absActive: frontSlip > 0.15 && brake > 0.75,
      tcActive: throttle > 0.85 && Math.abs(r.steeringRad) > 0.25,
      offTrackRisk: 0.1,
      hazardAhead: false,
      hazardDistanceM: 999,
      hazardDescription: '',
      flagState: 'green',
    });
  }

  const lapTime = Math.round((track.referenceLapTimeSec + cumulativeDelta) * 1000) / 1000;
  return {
    lapNumber: 1,
    lapTimeSec: lapTime,
    sector1Sec: Math.round(lapTime * 0.24 * 1000) / 1000,
    sector2Sec: Math.round(lapTime * 0.41 * 1000) / 1000,
    sector3Sec: Math.round(lapTime * 0.35 * 1000) / 1000,
    valid: true,
    maxSpeedKmh: Math.max(...frames.map((f) => f.speedKmh)),
    avgTrailBrakeScore: 76,
    frames,
  };
}
