function interpolatePoints(
  pts: Array<{ pct: number; x: number; y: number }>,
  lapDistPct: number
): { x: number; y: number } {
  if (pts.length === 0) return { x: 500, y: 270 };
  const pct = ((lapDistPct % 1) + 1) % 1;
  for (let i = 0; i < pts.length; i++) {
    const cur = pts[i];
    const next = pts[(i + 1) % pts.length];
    const nextPct = i === pts.length - 1 ? 1.0 : next.pct;
    if (pct >= cur.pct && pct <= nextPct) {
      const span = Math.max(0.0001, nextPct - cur.pct);
      const t = (pct - cur.pct) / span;
      return {
        x: Math.round((cur.x + (next.x - cur.x) * t) * 10) / 10,
        y: Math.round((cur.y + (next.y - cur.y) * t) * 10) / 10,
      };
    }
  }
  return { x: pts[0].x, y: pts[0].y };
}

